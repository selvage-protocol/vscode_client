#!/usr/bin/env bash
#
# Installs this checkout's git hook and checks that the Nix store paths it embeds still resolve.
#
#   scripts/hooks.sh
#
# The hook set is not this repository's: `.pre-commit-config.yaml` is written by the
# `reference_server` dev shell (`git-hooks.nix`), and this repository's own flake deliberately
# declares none. Of that set only the pre-push stage applies here, where it is four file-hygiene
# checks. The pre-commit stage is the server's Rust set: its `audit`, `cargo nextest`, `tarpaulin`
# and `typos` hooks fail in a JavaScript checkout, so a pre-commit hook installed here makes every
# commit need `--no-verify`. This script removes that one and the commit-msg one, and installs
# pre-push.
#
# `pre-commit install` writes the interpreter and the `pre-commit` binary into the hook as
# absolute `/nix/store` paths. Garbage collection removes a store path nothing else references,
# and from then on every push dies with `No such file or directory` before the hook runs. The
# check at the end names the hook and the path instead of leaving that message behind.
set -euo pipefail

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"

if [ -L .pre-commit-config.yaml ] && [ ! -e .pre-commit-config.yaml ]; then
  printf '%s points at %s, which does not exist\n' .pre-commit-config.yaml "$(readlink .pre-commit-config.yaml)" >&2
  exit 1
fi

if [ ! -e .pre-commit-config.yaml ]; then
  printf "no .pre-commit-config.yaml here: the hook set is the reference_server dev shell's\n" >&2
  exit 0
fi

run_pre_commit() {
  if command -v pre-commit >/dev/null 2>&1; then
    pre-commit "$@"
  else
    nix shell nixpkgs#pre-commit -c pre-commit "$@"
  fi
}

hooks_dir=$(git rev-parse --git-path hooks)

# A dev shell entered from this checkout lands the whole set. Drop the stages this repository
# cannot run, and only when the file is one `pre-commit` generated.
for hook in pre-commit commit-msg; do
  file="$hooks_dir/$hook"
  if [ -f "$file" ] && grep -q 'File generated by pre-commit' "$file"; then
    rm "$file"
    printf 'removed %s: only the pre-push stage applies here\n' "$file"
  fi
done

# `pre-commit install` refuses to run while `core.hooksPath` is set, and the dev shell leaves it
# set to the default `.git/hooks`, where the install would go anyway. Drop that local setting
# rather than let it block the install. A value from a global or system config stays, and
# `pre-commit` itself reports it.
if [ "$(git config --get core.hooksPath || true)" = ".git/hooks" ]; then
  git config --local --unset-all core.hooksPath >/dev/null 2>&1 || true
fi

run_pre_commit install --hook-type pre-push

# The hook is a shell script that execs a store path, so a path that does not exist is the whole
# of the failure. `grep` stops at the quote or space that ends each path.
missing=0
for file in "$hooks_dir"/*; do
  case "$file" in *.sample) continue ;; esac
  [ -f "$file" ] || continue
  while read -r path; do
    if [ ! -e "$path" ]; then
      printf '%s references %s, which does not exist\n' "$file" "$path" >&2
      missing=1
    fi
  done < <(grep -o '/nix/store/[^ "]*' "$file" || true)
done
exit "$missing"
